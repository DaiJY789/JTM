def load_and_sample(
    dataset_root: Path,
    split: str,
    sample_size: int,
    seed: int,
    images_per_sample: int = MAX_IMAGES_PER_SAMPLE,
) -> list[dict[str, Any]]:
    metadata_path = dataset_root / "dataset_metadata.json"
    records = json.loads(metadata_path.read_text(encoding="utf-8"))
    candidates = [item for item in records if str(item.get("split")) == split]
    if sample_size > len(candidates):
        raise ValueError(f"sample_size={sample_size} exceeds split size {len(candidates)}")
    rng = random.Random(seed)
    selected = rng.sample(candidates, sample_size)
    manifest = []
    for item in selected:
        image_paths = [str(path) for path in item.get("image_paths", [])]
        if not image_paths:
            raise ValueError(f"sample {item.get('sample_id')} has no image_paths")
        selected_indices = select_sample_image_indices(
            len(image_paths), images_per_sample, rng
        )
        selected_images = [image_paths[index] for index in selected_indices]
        selected_labels = [f"Image {index + 1}" for index in selected_indices]
        selected_image = selected_images[0]
        absolute_images = [(dataset_root / path).resolve() for path in selected_images]
        for absolute_image in absolute_images:
            if not absolute_image.is_file():
                raise FileNotFoundError(absolute_image)
        manifest.append(
            {
                "sample_id": str(item.get("sample_id")),
                "split": str(item.get("split")),
                "text": str(item.get("text") or ""),
                "image_paths": image_paths,
                "selected_image_path": selected_image,
                "selected_image_absolute_path": str(absolute_images[0]),
                "selected_image_paths": selected_images,
                "selected_image_labels": selected_labels,
                "selected_image_absolute_paths": [str(path) for path in absolute_images],
                "available_image_count": len(image_paths),
                "selected_image_count": len(selected_images),
                "expected_verdict": str(item.get("verdict") or ""),
                "rationale": str(item.get("rationale") or ""),
                "distortion_taxonomy": list(item.get("distortion_taxonomy") or []),
                "language_code": str(item.get("language_code") or ""),
                "region_code": str(item.get("region_code") or ""),
                "theme_category": str(item.get("theme_category") or ""),
            }
        )
    return manifest


def load_fixed_manifest(
    manifest_path: Path,
    dataset_root: Path,
    images_per_sample: int = MAX_IMAGES_PER_SAMPLE,
) -> tuple[list[dict[str, Any]], str, int]:
    payload = json.loads(manifest_path.read_text(encoding="utf-8"))
    samples = payload.get("samples") if isinstance(payload, dict) else None
    if not isinstance(samples, list) or not samples:
        raise ValueError(f"fixed manifest has no samples: {manifest_path}")
    materialized = []
    seen_ids = set()
    for source in samples:
        if not isinstance(source, dict):
            raise ValueError("fixed manifest samples must be JSON objects")
        sample_id = str(source.get("sample_id") or "")
        if not sample_id or sample_id in seen_ids:
            raise ValueError(f"missing or duplicate sample_id in fixed manifest: {sample_id!r}")
        seen_ids.add(sample_id)
        image_paths = [str(path) for path in source.get("image_paths", []) if str(path).strip()]
        legacy_selected_image = str(source.get("selected_image_path") or "")
        if not image_paths and legacy_selected_image:
            image_paths = [legacy_selected_image]
        if not image_paths:
            raise ValueError(f"sample {sample_id} has no image_paths")
        image_rng = random.Random(f"{int(payload.get('seed') or 0)}:{sample_id}:images")
        selected_indices = select_sample_image_indices(
            len(image_paths), images_per_sample, image_rng
        )
        selected_images = [image_paths[index] for index in selected_indices]
        selected_labels = [f"Image {index + 1}" for index in selected_indices]
        selected_image = selected_images[0] if selected_images else ""
        absolute_images = [(dataset_root / path).resolve() for path in selected_images]
        if any(not path.is_file() for path in absolute_images):
            missing_path = next(path for path in absolute_images if not path.is_file())
            raise FileNotFoundError(missing_path)
        expected_verdict = str(source.get("expected_verdict") or source.get("verdict") or "")
        if expected_verdict not in DATASET_LABELS:
            raise ValueError(f"invalid expected_verdict for sample {sample_id}: {expected_verdict!r}")
        materialized.append(
            {
                **source,
                "sample_id": sample_id,
                "split": str(payload.get("name") or payload.get("source_split") or "fixed_manifest"),
                "selected_image_absolute_path": str(absolute_images[0]),
                "selected_image_paths": selected_images,
                "selected_image_labels": selected_labels,
                "selected_image_absolute_paths": [str(path) for path in absolute_images],
                "available_image_count": len(image_paths),
                "selected_image_count": len(selected_images),
                "expected_verdict": expected_verdict,
            }
        )
    return materialized, str(payload.get("name") or "fixed_manifest"), int(payload.get("seed") or 0)


def select_sample_images(
    image_paths: list[str],
    images_per_sample: int,
    rng: random.Random,
) -> list[str]:
    """Keep every image up to the cap; sample without losing original order."""
    return [
        image_paths[index]
        for index in select_sample_image_indices(len(image_paths), images_per_sample, rng)
    ]


def select_sample_image_indices(
    image_count: int,
    images_per_sample: int,
    rng: random.Random,
) -> list[int]:
    """Return original indices so sampled images retain stable source labels."""
    limit = max(1, min(MAX_IMAGES_PER_SAMPLE, int(images_per_sample)))
    if image_count <= limit:
        return list(range(image_count))
    return sorted(rng.sample(range(image_count), limit))


def extract_text_label(result: dict[str, Any]) -> str | None:
    mfc_detection = (result.get("mfc_detection") or result.get("mmd_detection"))
    if isinstance(mfc_detection, dict):
        verdict = str(mfc_detection.get("label") or mfc_detection.get("verdict") or "").strip()
        if verdict in DATASET_LABELS:
            return verdict
    final_label = str(result.get("label") or "").strip()
    if final_label in DATASET_LABELS:
        return final_label
    return NO_VERDICT


def compact_result(result: dict[str, Any]) -> dict[str, Any]:
    crossmodal = (
        result.get("crossmodal_verdict")
        if isinstance(result.get("crossmodal_verdict"), dict)
        else {}
    )
    raw = result.get("raw") if isinstance(result.get("raw"), dict) else {}
    tool_context = (raw.get("mfc_tool_evidence") or raw.get("mmd_tool_evidence")) if isinstance((raw.get("mfc_tool_evidence") or raw.get("mmd_tool_evidence")), dict) else {}
    ocr = tool_context.get("ocr") if isinstance(tool_context.get("ocr"), dict) else {}
    search = tool_context.get("search") if isinstance(tool_context.get("search"), dict) else {}
    mfc_detection = (result.get("mfc_detection") or result.get("mmd_detection")) if isinstance((result.get("mfc_detection") or result.get("mmd_detection")), dict) else {}
    return {
        "final_label": result.get("label"),
        "final_type": result.get("type"),
        "final_confidence": result.get("confidence"),
        "summary": result.get("summary", ""),
        "decision_status": result.get("decision_status") or mfc_detection.get("decision_status"),
        "mfc_detection": {
            "status": mfc_detection.get("status"),
            "label": mfc_detection.get("label") or mfc_detection.get("verdict"),
            "type": mfc_detection.get("type"),
            "confidence": mfc_detection.get("confidence"),
            "atomic_points": mfc_detection.get("atomic_points", []),
            "fine_grained_checks": mfc_detection.get("fine_grained_checks", {}),
            "evidence": mfc_detection.get("evidence", []),
            "user_answer": mfc_detection.get("user_answer", mfc_detection.get("explanation", {})),
        },
        "crossmodal_verdict": {
            "label": crossmodal.get("label"),
            "consistency_score": crossmodal.get("consistency_score"),
            "matched_elements": crossmodal.get("matched_elements", []),
            "mismatched_elements": crossmodal.get("mismatched_elements", []),
            "missing_elements": crossmodal.get("missing_elements", []),
            "reasoning": crossmodal.get("reasoning", ""),
            "limitations": crossmodal.get("limitations", []),
        },
        "limitations": result.get("report", {}).get("limitations", [])
        if isinstance(result.get("report"), dict)
        else [],
        "tool_evidence_summary": {
            "enabled": bool(tool_context.get("enabled")),
            "ocr_status": ocr.get("status"),
            "ocr_text_characters": len(str(ocr.get("ocr_text") or "")),
            "search_status": search.get("status"),
            "search_queries": search.get("queries", []),
            "search_result_count": len(search.get("results", []))
            if isinstance(search.get("results"), list)
            else 0,
            "candidate_image_count": len(search.get("images", []))
            if isinstance(search.get("images"), list)
            else 0,
        },
        "diagnostics": (raw.get("mfc_diagnostics") or raw.get("mmd_diagnostics", {})),
        "timings": raw.get("timings", {}),
    }


def evaluate_one(item: dict[str, Any]) -> tuple[dict[str, Any], dict[str, Any]]:
    started_at = time.perf_counter()
    sample_id = item["sample_id"]
    try:
        image_paths = item.get("selected_image_absolute_paths") or [
            item["selected_image_absolute_path"]
        ]
        image_contents = [Path(path).read_bytes() for path in image_paths]
        result = get_detection_orchestrator().detect(
            task_type=DetectionTaskType.MULTIMODAL_FACT_CHECKING,
            text=item["text"],
            image_content=image_contents[0],
            image_contents=image_contents,
            image_labels=item.get("selected_image_labels"),
            question="请结合新闻文本和所选配图进行多模态事实核查。",
            language="zh",
        )
        text_label = extract_text_label(result)
        predicted_verdict = text_label if text_label in DATASET_LABELS else NO_VERDICT
        expected_verdict = item["expected_verdict"]
        correct = predicted_verdict == expected_verdict
        ordinal_distance = (
            abs(LABEL_TO_INDEX[predicted_verdict] - LABEL_TO_INDEX[expected_verdict])
            if predicted_verdict in LABEL_TO_INDEX and expected_verdict in LABEL_TO_INDEX
            else None
        )
        compact = compact_result(result)
        mfc_detection = (result.get("mfc_detection") or result.get("mmd_detection")) if isinstance((result.get("mfc_detection") or result.get("mmd_detection")), dict) else {}
        technical_success = not mfc_detection or mfc_detection.get("status") == "success"
        record = {
            **item,
            "status": "completed" if technical_success else "technical_error",
            "system_text_label": text_label,
            "predicted_verdict": predicted_verdict,
            "correct": correct,
            "ordinal_distance": ordinal_distance,
            "runtime_seconds": round(time.perf_counter() - started_at, 3),
            "prediction": compact,
            "error": "" if technical_success else str(mfc_detection.get("error") or result.get("summary") or ""),
        }
        return record, result
    except Exception as exc:
        record = {
            **item,
            "status": "error",
            "system_text_label": "",
            "predicted_verdict": NO_VERDICT,
            "correct": False,
            "ordinal_distance": None,
            "runtime_seconds": round(time.perf_counter() - started_at, 3),
            "prediction": {},
            "error": f"{type(exc).__name__}: {exc}",
        }
        return record, {}


def summarize(
    records: list[dict[str, Any]],
    *,
    seed: int,
    split: str,
    requested_sample_size: int,
) -> dict[str, Any]:
    completed = [item for item in records if item.get("status") == "completed"]
    technical_failures = [item for item in records if item.get("status") != "completed"]
    mapped = [item for item in records if item.get("predicted_verdict") in DATASET_LABELS]
    correct_count = sum(bool(item.get("correct")) for item in records)
    confusion_columns = [*DATASET_LABELS, NO_VERDICT_COLUMN]
    confusion = {
        expected: {predicted: 0 for predicted in confusion_columns}
        for expected in DATASET_LABELS
    }
    for item in records:
        expected = item.get("expected_verdict")
        predicted = item.get("predicted_verdict")
        predicted_column = predicted if predicted in DATASET_LABELS else NO_VERDICT_COLUMN
        if expected in confusion:
            confusion[expected][predicted_column] += 1
    by_expected = {}
    for label in DATASET_LABELS:
        items = [item for item in records if item.get("expected_verdict") == label]
        by_expected[label] = {
            "count": len(items),
            "correct": sum(bool(item.get("correct")) for item in items),
            "accuracy": round(sum(bool(item.get("correct")) for item in items) / len(items), 4)
            if items
            else None,
        }
    distances = [item["ordinal_distance"] for item in mapped if item.get("ordinal_distance") is not None]
    runtimes = [float(item.get("runtime_seconds") or 0.0) for item in records]
    sorted_runtimes = sorted(runtimes)

    def percentile(values: list[float], quantile: float) -> float | None:
        if not values:
            return None
        position = (len(values) - 1) * quantile
        lower = int(position)
        upper = min(lower + 1, len(values) - 1)
        fraction = position - lower
        return values[lower] + (values[upper] - values[lower]) * fraction

    image_counts = [
        len(item["selected_image_paths"])
        for item in records
        if isinstance(item.get("selected_image_paths"), list)
    ]
    image_groups = {}
    for name, predicate in (
        ("up_to_4", lambda item: int(item.get("available_image_count") or 0) <= 4),
        ("over_4", lambda item: int(item.get("available_image_count") or 0) > 4),
    ):
        group = [item for item in records if predicate(item)]
        image_groups[name] = {
            "count": len(group),
            "correct": sum(bool(item.get("correct")) for item in group),
            "accuracy": round(
                sum(bool(item.get("correct")) for item in group) / len(group), 4
            )
            if group
            else None,
        }
    no_han = [
        item for item in records if not re.search(r"[一-龥]", str(item.get("text") or ""))
    ]
    per_class_metrics = {}
    for label in DATASET_LABELS:
        true_positive = confusion[label][label]
        false_positive = sum(confusion[expected][label] for expected in DATASET_LABELS if expected != label)
        false_negative = sum(count for predicted, count in confusion[label].items() if predicted != label)
        precision = true_positive / (true_positive + false_positive) if true_positive + false_positive else 0.0
        recall = true_positive / (true_positive + false_negative) if true_positive + false_negative else 0.0
        f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
        per_class_metrics[label] = {
            "precision": round(precision, 4),
            "recall": round(recall, 4),
            "f1": round(f1, 4),
        }
    macro_f1 = sum(item["f1"] for item in per_class_metrics.values()) / len(DATASET_LABELS)
    confidence_items = []
    for item in mapped:
        confidence = item.get("prediction", {}).get("final_confidence")
        if isinstance(confidence, (int, float)):
            confidence_items.append((float(confidence), 1.0 if item.get("correct") else 0.0))
    brier_score = (
        sum((confidence - outcome) ** 2 for confidence, outcome in confidence_items) / len(confidence_items)
        if confidence_items
        else None
    )
    expected_calibration_error = 0.0
    calibration_bins = []
    if confidence_items:
        for index in range(10):
            lower = index / 10
            upper = (index + 1) / 10
            values = [
                pair for pair in confidence_items
                if (lower <= pair[0] <= upper if index == 9 else lower <= pair[0] < upper)
            ]
            if not values:
                continue
            mean_confidence = sum(pair[0] for pair in values) / len(values)
            accuracy = sum(pair[1] for pair in values) / len(values)
            expected_calibration_error += len(values) / len(confidence_items) * abs(mean_confidence - accuracy)
            calibration_bins.append(
                {
                    "range": [round(lower, 1), round(upper, 1)],
                    "count": len(values),
                    "mean_confidence": round(mean_confidence, 4),
                    "accuracy": round(accuracy, 4),
                }
            )
    return {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "dataset": "MFC",
        "split": split,
        "seed": seed,
        "requested_sample_size": requested_sample_size,
        "evaluated_count": len(records),
        "completed_count": len(completed),
        "error_count": len(technical_failures),
        "technical_success_rate": round(len(completed) / len(records), 4) if records else 0.0,
        "mapped_count": len(mapped),
        "coverage": round(len(mapped) / len(records), 4) if records else 0.0,
        "correct_count": correct_count,
        "exact_accuracy": round(correct_count / len(records), 4) if records else 0.0,
        "mapped_only_accuracy": round(correct_count / len(mapped), 4) if mapped else 0.0,
        "within_one_class_accuracy": round(
            sum(distance <= 1 for distance in distances) / len(distances), 4
        )
        if distances
        else 0.0,
        "mean_absolute_class_distance": round(sum(distances) / len(distances), 4)
        if distances
        else None,
        "macro_f1": round(macro_f1, 4),
        "per_class_metrics": per_class_metrics,
        "confidence_calibration": {
            "brier_score": round(brier_score, 4) if brier_score is not None else None,
            "expected_calibration_error": round(expected_calibration_error, 4) if confidence_items else None,
            "bins": calibration_bins,
        },
        "decision_status_distribution": dict(
            Counter(
                item.get("prediction", {}).get("decision_status") or "missing"
                for item in records
            )
        ),
        "runtime_seconds": {
            "mean_per_case": round(statistics.mean(runtimes), 3) if runtimes else None,
            "median_per_case": round(statistics.median(runtimes), 3) if runtimes else None,
            "min_per_case": round(min(runtimes), 3) if runtimes else None,
            "max_per_case": round(max(runtimes), 3) if runtimes else None,
            "p90_per_case": round(percentile(sorted_runtimes, 0.90), 3)
            if runtimes
            else None,
            "p95_per_case": round(percentile(sorted_runtimes, 0.95), 3)
            if runtimes
            else None,
            "over_20_seconds_count": sum(value > 20 for value in runtimes),
            "sum_case_runtime": round(sum(runtimes), 3) if runtimes else 0.0,
        },
        "input_image_count_distribution": dict(Counter(image_counts)),
        "accuracy_by_available_image_count_group": image_groups,
        "text_language_profile": {
            "contains_han_count": len(records) - len(no_han),
            "no_han_count": len(no_han),
            "no_han_sample_ids": [str(item.get("sample_id") or "") for item in no_han],
        },
        "expected_distribution": dict(Counter(item.get("expected_verdict") for item in records)),
        "predicted_distribution": dict(Counter(item.get("predicted_verdict") for item in records)),
        "system_text_label_distribution": dict(
            Counter(item.get("system_text_label") or "error" for item in records)
        ),
        "crossmodal_label_distribution": dict(
            Counter(
                item.get("prediction", {}).get("crossmodal_verdict", {}).get("label") or "missing"
                for item in records
            )
        ),
        "accuracy_by_expected_verdict": by_expected,
        "confusion_matrix": confusion,
        "failure_policy": "Timeouts, invalid JSON, and call failures produce a null verdict and count as technical errors.",
    }


def write_csv(path: Path, records: list[dict[str, Any]]) -> None:
    fields = [
        "sample_id",
        "expected_verdict",
        "system_text_label",
        "predicted_verdict",
        "correct",
        "ordinal_distance",
        "final_label",
        "confidence",
        "decision_status",
        "crossmodal_label",
        "consistency_score",
        "runtime_seconds",
        "selected_image_path",
        "selected_image_paths",
        "selected_image_labels",
        "status",
        "error",
    ]
    with path.open("w", encoding="utf-8-sig", newline="") as file:
        writer = csv.DictWriter(file, fieldnames=fields)
        writer.writeheader()
        for item in records:
            prediction = item.get("prediction", {})
            mfc = prediction.get("mfc_detection", {})
            crossmodal = prediction.get("crossmodal_verdict", {})
            writer.writerow(
                {
                    "sample_id": item.get("sample_id"),
                    "expected_verdict": item.get("expected_verdict"),
                    "system_text_label": item.get("system_text_label"),
                    "predicted_verdict": item.get("predicted_verdict"),
                    "correct": item.get("correct"),
                    "ordinal_distance": item.get("ordinal_distance"),
                    "final_label": prediction.get("final_label"),
                    "confidence": mfc.get("confidence"),
                    "decision_status": prediction.get("decision_status"),
                    "crossmodal_label": crossmodal.get("label"),
                    "consistency_score": crossmodal.get("consistency_score"),
                    "runtime_seconds": item.get("runtime_seconds"),
                    "selected_image_path": item.get("selected_image_path"),
                    "selected_image_paths": " | ".join(item.get("selected_image_paths", [])),
                    "selected_image_labels": " | ".join(item.get("selected_image_labels", [])),
                    "status": item.get("status"),
                    "error": item.get("error"),
                }
            )


