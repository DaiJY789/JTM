def read_existing(path: Path) -> dict[str, dict[str, Any]]:
    if not path.is_file():
        return {}
    records = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        item = json.loads(line)
        records[str(item["sample_id"])] = item
    return records


def same_evaluation_input(existing: dict[str, Any], current: dict[str, Any]) -> bool:
    """Do not resume a stale single-image result after the image-selection policy changes."""
    existing_images = existing.get("selected_image_paths")
    if not isinstance(existing_images, list):
        legacy_image = str(existing.get("selected_image_path") or "")
        existing_images = [legacy_image] if legacy_image else []
    existing_labels = existing.get("selected_image_labels")
    current_labels = current.get("selected_image_labels")
    labels_match = (
        existing_labels == current_labels
        if existing_labels is not None or current_labels is not None
        else True
    )
    return (
        existing_images == current.get("selected_image_paths", [])
        and labels_match
        and str(existing.get("text") or "") == str(current.get("text") or "")
    )


def format_confidence(record: dict[str, Any]) -> str:
    prediction = record.get("prediction")
    confidence = prediction.get("final_confidence") if isinstance(prediction, dict) else None
    if not isinstance(confidence, (int, float)):
        return "None"
    return f"{float(confidence):.4f}"


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    image_limit = max(1, min(MAX_IMAGES_PER_SAMPLE, args.images_per_sample))
    output_dir = args.output_dir.resolve()
    raw_dir = output_dir / "raw"
    output_dir.mkdir(parents=True, exist_ok=True)
    raw_dir.mkdir(parents=True, exist_ok=True)
    manifest_path = output_dir / "sample_manifest.json"
    results_path = output_dir / "results.jsonl"
    summary_path = output_dir / "summary.json"
    csv_path = output_dir / "results.csv"
    report_path = output_dir / "report.md"

    dataset_root = args.dataset_root.resolve()
    if args.manifest:
        manifest, run_split, run_seed = load_fixed_manifest(
            args.manifest.resolve(),
            dataset_root,
            images_per_sample=image_limit,
        )
    else:
        manifest = load_and_sample(
            dataset_root,
            args.split,
            args.sample_size,
            args.seed,
            images_per_sample=image_limit,
        )
        run_split = args.split
        run_seed = args.seed
    manifest_payload = {
        "dataset_root": str(dataset_root),
        "source_manifest": str(args.manifest.resolve()) if args.manifest else "",
        "split": run_split,
        "sample_size": len(manifest),
        "seed": run_seed,
        "images_per_sample": image_limit,
        "image_selection_policy": (
            "use_all_up_to_limit_else_seeded_random_sample_preserving_original_order_and_labels"
        ),
        "samples": manifest,
    }
    manifest_path.write_text(
        json.dumps(manifest_payload, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    run_manifest = manifest[: args.limit] if args.limit is not None else manifest
    if not args.resume:
        results_path.write_text("", encoding="utf-8")
    existing = read_existing(results_path) if args.resume else {}
    reusable = {
        item["sample_id"]: existing[item["sample_id"]]
        for item in run_manifest
        if item["sample_id"] in existing
        and existing[item["sample_id"]].get("status") == "completed"
        and same_evaluation_input(existing[item["sample_id"]], item)
    }
    ordered_records = [reusable[item["sample_id"]] for item in run_manifest if item["sample_id"] in reusable]
    pending = [item for item in run_manifest if item["sample_id"] not in reusable]
    write_lock = threading.Lock()
    print(
        f"MFC evaluation: selected={len(run_manifest)}, pending={len(pending)}, "
        f"workers={max(1, args.workers)}, seed={run_seed}, split={run_split}, "
        f"max_images_per_sample={image_limit}",
        flush=True,
    )

    def save_record(record: dict[str, Any], raw_result: dict[str, Any]) -> None:
        with write_lock:
            with results_path.open("a", encoding="utf-8") as file:
                file.write(json.dumps(record, ensure_ascii=False) + "\n")
            if raw_result:
                (raw_dir / f"{record['sample_id']}.json").write_text(
                    json.dumps(raw_result, ensure_ascii=False, indent=2), encoding="utf-8"
                )

    workers = max(1, min(4, args.workers))
    if workers == 1:
        for index, item in enumerate(pending, start=len(ordered_records) + 1):
            record, raw_result = evaluate_one(item)
            save_record(record, raw_result)
            ordered_records.append(record)
            print(
                f"[{index}/{len(run_manifest)}] id={record['sample_id']} "
                f"expected={record['expected_verdict']} predicted={record['predicted_verdict']} "
                f"confidence={format_confidence(record)} correct={record['correct']} "
                f"seconds={record['runtime_seconds']}",
                flush=True,
            )
    else:
        with ThreadPoolExecutor(max_workers=workers) as executor:
            futures = {executor.submit(evaluate_one, item): item for item in pending}
            for completed_index, future in enumerate(as_completed(futures), start=len(ordered_records) + 1):
                record, raw_result = future.result()
                save_record(record, raw_result)
                ordered_records.append(record)
                print(
                    f"[{completed_index}/{len(run_manifest)}] id={record['sample_id']} "
                    f"expected={record['expected_verdict']} predicted={record['predicted_verdict']} "
                    f"confidence={format_confidence(record)} correct={record['correct']} "
                    f"seconds={record['runtime_seconds']}",
                    flush=True,
                )

    by_id = {item["sample_id"]: item for item in ordered_records}
    ordered_records = [by_id[item["sample_id"]] for item in run_manifest if item["sample_id"] in by_id]
    results_path.write_text(
        "".join(json.dumps(item, ensure_ascii=False) + "\n" for item in ordered_records),
        encoding="utf-8",
    )
    summary = summarize(
        ordered_records,
        seed=run_seed,
        split=run_split,
        requested_sample_size=len(run_manifest),
    )
    summary_path.write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    write_csv(csv_path, ordered_records)
    write_report(report_path, summary)
    print(json.dumps(summary, ensure_ascii=False, indent=2), flush=True)
    print(f"Saved results to {output_dir}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
